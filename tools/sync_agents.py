"""Render native agent adapters from canonical role instructions; no API calls."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROLES = ("principal", "developer", "reviewer", "qa")


def rendered() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for role in ROLES:
        body = (ROOT / "agent-workflow" / "roles" / f"{role}.md").read_text().strip()
        description = f"Warmstart {role}; follow shared project instructions and evidence protocol."
        codex_name = f"warmstart-codex-{role}"
        outputs[ROOT / ".codex" / "agents" / f"{role}.toml"] = (
            "# Generated by tools/sync_agents.py; edit the canonical role instead.\n"
            f"name = {json.dumps(codex_name)}\n"
            f"description = {json.dumps(description)}\n"
            f"developer_instructions = {json.dumps(body)}\n"
        )
        for tool in ("cursor", "claude"):
            header = (
                "---\n"
                f"name: warmstart-{tool}-{role}\n"
                f"description: {json.dumps(description)}\n"
                "model: inherit\n"
            )
            if role == "reviewer":
                header += "readonly: true\n" if tool == "cursor" else "tools: Read, Glob, Grep\n"
            if tool == "claude" and role == "qa":
                header += "tools: Read, Glob, Grep, Bash\n"
            outputs[ROOT / f".{tool}" / "agents" / f"{role}.md"] = (
                header
                + "---\n\n<!-- Generated; edit agent-workflow/roles instead. -->\n\n"
                + body
                + "\n"
            )
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in rendered().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Outdated generated agents: " + ", ".join(stale))
    print("Agent adapters match canonical roles." if args.check else "Agent adapters generated.")


if __name__ == "__main__":
    main()
